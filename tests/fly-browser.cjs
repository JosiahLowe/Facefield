const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto((process.env.FACEFIELD_URL||'http://127.0.0.1:8000/')+'?seed=facefield');
 await page.waitForFunction(()=>document.querySelector('.fly').style.transform);
 const fly=page.locator('.fly');
 assert.equal(await fly.count(),1);
 assert.equal(await fly.getAttribute('aria-hidden'),'true');
 assert.equal(await fly.evaluate(e=>getComputedStyle(e).pointerEvents),'none');
 const box=await fly.boundingBox();
 assert.equal(box.width,28);assert.equal(box.height,28);
 await page.screenshot({path:'/tmp/facefield-fly.png'});
 const initial=await fly.getAttribute('style');await page.waitForTimeout(600);
 assert.notEqual(await fly.getAttribute('style'),initial,'fly is animated');
 const url=page.url();
 const world=page.locator('#world');
 const extent=await world.evaluate(w=>[w.scrollWidth,w.scrollHeight]);
 await world.evaluate(w=>w.scrollBy(1100,0));
 const leftBehind=await fly.boundingBox();
 assert.ok(leftBehind.x+leftBehind.width<0,'quick scroll leaves the fly offscreen behind the player');
 await page.waitForTimeout(250);
 assert.ok((await fly.boundingBox()).x<0,'catch-up is delayed');
 await page.waitForFunction(()=>document.querySelector('.fly').getBoundingClientRect().right>0,{},{timeout:10000});
 const entry=await fly.boundingBox();assert.ok(entry.x<90,'reenters from the direction it was left');
 await page.waitForFunction(()=>{const r=document.querySelector('.fly').getBoundingClientRect();return r.x>20&&r.right<innerWidth&&r.y>0&&r.bottom<innerHeight;},{},{timeout:10000});
 assert.deepEqual(await world.evaluate(w=>[w.scrollWidth,w.scrollHeight]),extent,'fly does not enlarge the world');
 assert.equal(page.url(),url);assert.equal(await page.locator('.face').count(),1152);
 await page.locator('#shuffle').tap();assert.equal(await fly.count(),1);
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(600);
 const still=await fly.getAttribute('style');await page.waitForTimeout(300);
 assert.equal(await fly.getAttribute('style'),still,'reduced motion stops flight');
 assert.equal(await page.locator('.fly-wing').first().evaluate(e=>getComputedStyle(e).animationName),'none');
 await page.emulateMedia({reducedMotion:'no-preference'});await page.waitForTimeout(700);
 assert.notEqual(await fly.getAttribute('style'),still,'flight resumes');
 assert.deepEqual(errors,[]);
 console.log('PASS fly browser: one small fly; world-space lag, delayed return from departure direction, unchanged world bounds, shuffle, reduced motion, and resume.');
 await browser.close();
})();
